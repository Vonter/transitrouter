#!/usr/bin/env python3
"""
Refreshes every Bengaluru live-data id mapping in one run. Downloads the
static feed behind each live source and rebuilds the mapping from it:

  1. Reclaim GTFS-RT fallback (maps.reclaim.city/bengaluru/rt)
     Static feed: https://maps.reclaim.city/gtfs/bengaluru.zip
     -> functions/api/bmtc/blr-reclaim-routes.js   { "BMTC:<hash>": "<route_short_name>" }
     Its stop ids are already Namma BMTC ids (same as data/blr stop ids), so
     no stop mapping is needed.

  2. Namma BMTC API (production.zophop.com: arrivals, route-live-info, ...)
     Catalog: scheduler_v4 routes (~105MB), matched to data/blr by geo + name
     -> functions/api/bmtc/blr-id-mapping.js   (scripts/build_blr_id_mapping.py)
     Legacy numeric gtfsRtRouteId values are carried over from the previous
     file (nothing current publishes them).

  3. Primary GTFS-RT feed (gtfs.bengawalk.com/rt/feed/rt.pb)
     It has no static feed of its own to download; its route ids are the
     legacy numeric ids kept in blr-id-mapping.js. The coverage report only
     says whether it currently has data.

Finishes with a coverage report: how many live Reclaim route and stop ids
resolve through the fresh mappings.

Usage: python3 scripts/refresh_blr_rt_mappings.py [--skip-namma] [--dry-run]
       [--distance-threshold-m 100] [--confirm-threshold-m 300]
Run it whenever BMTC adds routes or data/blr is regenerated.
"""
import argparse
import csv
import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import build_blr_id_mapping as namma  # noqa: E402

REPO_ROOT = Path(__file__).parent.parent
BMTC_FUNCTIONS = REPO_ROOT / 'functions' / 'api' / 'bmtc'
RECLAIM_ROUTES_PATH = BMTC_FUNCTIONS / 'blr-reclaim-routes.js'
RECLAIM_STATIC_URL = 'https://maps.reclaim.city/gtfs/bengaluru.zip'
RECLAIM_RT_URL = 'https://maps.reclaim.city/bengaluru/rt'
PRIMARY_RT_URL = 'https://gtfs.bengawalk.com/rt/feed/rt.pb'
USER_AGENT = 'transitrouter-mapping-refresh'


def http_get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={'User-Agent': USER_AGENT})
    with urllib.request.urlopen(req, timeout=300) as res:
        return res.read()


def build_reclaim_routes() -> dict:
    print(f'Downloading {RECLAIM_STATIC_URL} ...')
    data = http_get(RECLAIM_STATIC_URL)
    print(f'  {len(data) / 1e6:.1f}MB')
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        with z.open('routes.txt') as f:
            rows = list(csv.DictReader(io.TextIOWrapper(f, encoding='utf-8-sig')))
    mapping = {}
    for row in sorted(rows, key=lambda r: r['route_id']):
        name = (row.get('route_short_name') or '').strip() or row['route_id']
        mapping[row['route_id']] = name
    print(f'  {len(mapping)} routes ({len(set(mapping.values()))} distinct names)')
    return mapping


def write_reclaim_routes(mapping: dict):
    RECLAIM_ROUTES_PATH.write_text(
        '// Auto-generated by scripts/refresh_blr_rt_mappings.py — do not edit manually\n'
        '// Reclaim GTFS-RT route_id ("BMTC:<hash>") -> local route_short_name.\n'
        f'export default {json.dumps(mapping, separators=(",", ":"), ensure_ascii=False)};\n'
    )
    print(f'Wrote {RECLAIM_ROUTES_PATH}')


def js_default(path: Path) -> dict:
    return json.loads(re.search(r'export default (\{.*\});?\s*$', path.read_text(), re.DOTALL).group(1))


def coverage_report(reclaim_routes: dict):
    """How much of the live Reclaim feed resolves through the mappings now on disk."""
    print('\nCoverage against live feeds')
    try:
        vp = json.loads(http_get(f'{RECLAIM_RT_URL}/vehicle_positions.json'))
        tu = json.loads(http_get(f'{RECLAIM_RT_URL}/trip_updates.json'))
    except Exception as e:  # noqa: BLE001
        print(f'  Reclaim RT unavailable: {e}')
        vp = tu = None

    if vp is not None:
        idm = js_default(namma.JS_OUTPUT_PATH)
        local_stops = json.loads(namma.STOPS_PATH.read_text())
        live_routes = {e['vehicle']['trip']['routeId'] for e in vp['entity'] if 'trip' in e['vehicle']}
        to_name = [r for r in live_routes if r in reclaim_routes]
        to_legacy = [r for r in to_name if idm['routes'].get(reclaim_routes[r], '').split('|')[0]]
        stop_ids = {s['stopId'] for e in tu['entity'] for s in e['tripUpdate'].get('stopTimeUpdate', [])}
        print(f'  Reclaim routes on a trip: {len(live_routes)}')
        print(f'    -> known route name:         {len(to_name)}')
        print(f'    -> legacy gtfsRtRouteId:     {len(to_legacy)}')
        print(f'  Reclaim stop ids in trip updates: {len(stop_ids)}')
        print(f'    -> present in data/blr stops: {len(stop_ids & set(local_stops))}')
        print(f'    -> known to Namma id mapping: {len(stop_ids & set(idm["s"]))}')

    try:
        size = len(http_get(PRIMARY_RT_URL))
        state = 'EMPTY (header only)' if size < 100 else 'has data'
        print(f'  Primary feed {PRIMARY_RT_URL}: {size} bytes, {state}')
    except Exception as e:  # noqa: BLE001
        print(f'  Primary feed unavailable: {e}')


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--skip-namma', action='store_true', help='Only refresh the Reclaim route table')
    parser.add_argument('--dry-run', action='store_true', help='Download and report, write nothing')
    parser.add_argument('--distance-threshold-m', type=float, default=100)
    parser.add_argument('--confirm-threshold-m', type=float, default=300)
    parser.add_argument('--report', type=Path, default=namma.DEFAULT_REPORT_PATH)
    args = parser.parse_args()

    reclaim_routes = build_reclaim_routes()
    if not args.dry_run:
        write_reclaim_routes(reclaim_routes)

    if not args.skip_namma:
        route_ids, stop_ids, routes_map, stops_map, report = namma.build_mapping(
            args.distance_threshold_m, args.confirm_threshold_m,
        )
        print(f'Namma: matched {len(routes_map)} routes, touched {len(stops_map)} local stops')
        total = len(routes_map) + len(report['unmatched_no_candidate']) + len(report['unmatched_name_only'])
        namma.write_report(report, args.report, total, len(stops_map))
        if not args.dry_run:
            namma.write_js_module(route_ids, stop_ids, routes_map, stops_map)

    if args.dry_run:
        print('--dry-run: nothing written, coverage below reflects the files currently on disk')
    coverage_report(reclaim_routes)


if __name__ == '__main__':
    main()
