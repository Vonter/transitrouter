#!/usr/bin/env python3
"""Builds functions/api/ahmedabad/ahmedabad-id-mapping.js: translations between
the realtime feed's ids (the live gtfs.zip served next to rt.pb) and the local
ids (data/ahmedabad, built from amd-gtfs gtfs_compat.zip).

Both feeds share trip_ids, so ids are joined through trips rather than guessed:
  routes: live route_id (per direction) -> [route_short_name, compat route_id]
  stops:  live stop_id -> compat stop_id, only where they differ (compat merges
          duplicate stops); identity otherwise.
Stop mappings must be unambiguous (one compat stop per live stop) or the script fails.

Usage: python3 scripts/build_amd_id_mapping.py [--live PATH_OR_URL] [--compat PATH_OR_URL]
"""
import argparse, csv, io, json, urllib.request, zipfile
from collections import Counter, defaultdict
from pathlib import Path

LIVE = 'https://rt-bucket.blrtransit.com/rt-amd/control/static/gtfs.zip'
COMPAT = 'https://github.com/croyla/amd-gtfs/raw/refs/heads/main/gtfs_compat.zip'
OUT = Path(__file__).parent.parent / 'functions' / 'api' / 'ahmedabad' / 'ahmedabad-id-mapping.js'


def load(src):
    data = urllib.request.urlopen(src, timeout=180).read() if src.startswith('http') else Path(src).read_bytes()
    z = zipfile.ZipFile(io.BytesIO(data))
    return lambda name: csv.DictReader(io.TextIOWrapper(z.open(name), 'utf-8-sig'))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--live', default=LIVE)
    ap.add_argument('--compat', default=COMPAT)
    args = ap.parse_args()
    live, compat = load(args.live), load(args.compat)

    compat_routes = {r['route_id']: r for r in compat('routes.txt')}
    compat_stops = {r['stop_id'] for r in compat('stops.txt')}
    live_trip_route = {t['trip_id']: t['route_id'] for t in live('trips.txt')}

    votes = defaultdict(Counter)
    for t in compat('trips.txt'):
        lr = live_trip_route.get(t['trip_id'])
        if lr:
            votes[lr][t['route_id']] += 1
    routes = {}
    for lr, c in sorted(votes.items()):
        cr = c.most_common(1)[0][0]
        routes[lr] = [compat_routes[cr]['route_short_name'], cr]
    missing = set(live_trip_route.values()) - set(routes)
    if missing:
        print(f'warning: {len(missing)} live routes have no compat trips: {sorted(missing)[:10]}')

    compat_seq = defaultdict(dict)
    for r in compat('stop_times.txt'):
        compat_seq[r['trip_id']][r['stop_sequence']] = r['stop_id']
    svotes = defaultdict(Counter)
    for r in live('stop_times.txt'):
        cs = compat_seq.get(r['trip_id'], {}).get(r['stop_sequence'])
        if cs:
            svotes[r['stop_id']][cs] += 1
    stops = {}
    for ls, c in sorted(svotes.items()):
        top = c.most_common(1)[0][0]
        if top != ls or ls not in compat_stops:
            if len(c) > 1:
                raise SystemExit(f'ambiguous stop {ls}: {c.most_common(3)}')
            stops[ls] = top

    body = json.dumps({'routes': routes, 'stops': stops}, separators=(',', ':'), ensure_ascii=False)
    OUT.write_text(
        '// Auto-generated by scripts/build_amd_id_mapping.py — do not edit manually\n'
        '// Translates the Ahmedabad GTFS-RT feed ids to local (gtfs_compat) ids.\n'
        '//   routes[liveRouteId] = [publicRouteNumber, localRouteId]\n'
        '//   stops[liveStopId]   = localStopId (only where they differ)\n'
        f'export default {body};\n'
    )
    print(f'{len(routes)} routes, {len(stops)} stop translations -> {OUT}')


main()
